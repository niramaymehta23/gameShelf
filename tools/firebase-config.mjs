// Writes public/js/firebase-config.js, which is git-ignored so the project's settings never live in the repo.
//
//   node tools/firebase-config.mjs          real settings for the project in .firebaserc (runs before every deploy;
//                                           needs `npx firebase login`). App Check site key from .env.
//   node tools/firebase-config.mjs --stub   placeholder for local use, only if the file doesn't exist yet
//                                           (the emulators don't need real settings; see net.js)

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public/js/firebase-config.js');
const HEAD = `'use strict';
// Generated by tools/firebase-config.mjs — do not edit, do not commit.
// These values are public by design (every visitor's browser receives them). The API key is restricted
// to the site's addresses, App Check only lets the real site through, and the rules guard the data.
`;

if (process.argv.includes('--stub')) {
  if (!fs.existsSync(OUT)) fs.writeFileSync(OUT, HEAD + 'const FIREBASE_CONFIG = null;\nconst FIREBASE_APPCHECK_KEY = null;\n');
  process.exit(0);
}

try { process.loadEnvFile(path.join(ROOT, '.env')); } catch (e) {}
const raw = execFileSync('npx', ['firebase', 'apps:sdkconfig', 'WEB', '--json'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
const { status, result } = JSON.parse(raw);
if (status !== 'success') throw new Error('could not read the Firebase web app settings');
const { apiKey, authDomain, databaseURL, projectId, storageBucket, messagingSenderId, appId } = result.sdkConfig;
const config = { apiKey, authDomain, databaseURL, projectId, storageBucket, messagingSenderId, appId };
const siteKey = process.env.APPCHECK_SITE_KEY || null;
if (!siteKey) console.warn('firebase-config: APPCHECK_SITE_KEY is not set in .env, so App Check is off');

fs.writeFileSync(OUT, HEAD + `const FIREBASE_CONFIG = ${JSON.stringify(config, null, 2)};\nconst FIREBASE_APPCHECK_KEY = ${JSON.stringify(siteKey)};\n`);
console.log(`firebase-config: wrote settings for ${projectId}${siteKey ? ' with App Check' : ''}`);
